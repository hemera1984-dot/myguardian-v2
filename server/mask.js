// AI로 나가기 전에 번호를 가린다(2026-10-13 AI 입력). 전화·주민번호·계좌·카드처럼 긴 번호만 — 날짜(2026-10-15)·시각·금액은 그대로 둔다.
export function 번호가리기(s) {
  return String(s || "")
    .replace(/(?<!\d)\d{6}[\s-]?[1-8]\d{6}(?!\d)/g, "[번호]")                       // 주민·외국인등록번호
    .replace(/(?<!\d)0\d{1,2}[\s.-]?\d{3,4}[\s.-]?\d{4}(?!\d)/g, "[번호]")            // 전화
    .replace(/(?<!\d)\d{4}[\s-]\d{4}[\s-]\d{4}[\s-]\d{2,4}(?!\d)/g, "[번호]")          // 카드
    .replace(/(?<!\d)\d(?:-?\d){9,}(?!\d)/g, "[번호]");                               // 열 자리 넘는 계좌 등
}

// node mask.js 로 돌리면 스스로 점검한다
if (process.argv[1] && process.argv[1].endsWith("mask.js")) {
  const 같다 = (입력, 기대) => { const 결과 = 번호가리기(입력); if (결과 !== 기대) { console.error("틀림:", 입력, "→", 결과, "(기대", 기대 + ")"); process.exit(1); } };
  같다("김민수 010-1234-5678 통화", "김민수 [번호] 통화");
  같다("01012345678", "[번호]");
  같다("02 345 6789", "[번호]");
  같다("900101-1234567", "[번호]");
  같다("계좌 110-123-456789", "계좌 [번호]");
  같다("카드 1234 5678 9012 3456", "카드 [번호]");
  같다("2026-10-15 10시 미팅", "2026-10-15 10시 미팅");
  같다("다음 주 수요일 3시, 보험료 120000원", "다음 주 수요일 3시, 보험료 120000원");
  같다("10/15 오후 2시 30분", "10/15 오후 2시 30분");
  console.log("번호 가리기 점검 통과");
}
